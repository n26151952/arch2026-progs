static uint8_t pdb_distance_at(uint32_t rank)
{
    uint8_t packed = pdb_data[rank >> 1];
    uint32_t shift = (rank & 1U) << 2;
    return (uint8_t) ((packed >> shift) & 0x0fU);
}
#define FOR_EACH_CUBIE(M) \
    M(0);                 \
    M(1);                 \
    M(2);                 \
    M(3);                 \
    M(4);                 \
    M(5);                 \
    M(6)
static void apply_move_to(const state_t *state, uint8_t move, state_t *result)
{
    const uint8_t *source_row = move_source[move];
    const uint8_t *twist_row = move_twist[move];
#define APPLY_CORNER(i)                                                   \
    do {                                                                  \
        uint8_t from = source_row[i];                                     \
        const uint8_t *source_permutation = &state->p[from];              \
        const uint8_t *source_orientation = &state->o[from];              \
        result->p[i] = source_permutation[0];                             \
        uint8_t value = (uint8_t) (source_orientation[0] + twist_row[i]); \
        result->o[i] = value >= 3U ? (uint8_t) (value - 3U) : value;      \
    } while (0)
    FOR_EACH_CUBIE(APPLY_CORNER);
#undef APPLY_CORNER
}
static uint32_t pattern_rank(const state_t *state)
{
    uint8_t mask = 0, orientation_key = 0;
    uint16_t permutation_key = 0;
#define TRACK_CUBIE(i)                                                      \
    do {                                                                    \
        uint8_t corner = state->p[i];                                       \
        if (corner < 4U) {                                                  \
            mask |= (uint8_t) (1U << (i));                                  \
            permutation_key = (uint16_t) ((permutation_key << 3) | corner); \
            orientation_key =                                               \
                (uint8_t) ((orientation_key << 2) | state->o[i]);           \
        }                                                                   \
    } while (0)
    FOR_EACH_CUBIE(TRACK_CUBIE);
#undef TRACK_CUBIE
#undef FOR_EACH_CUBIE
    uint32_t placement = (uint32_t) comb_rank_by_mask[mask] * 24U +
                         perm_rank_by_key[permutation_key];
    return placement * 81U + orientation_rank_by_key[orientation_key];
}
static int is_solved(const state_t *state)
{
    if (state == NULL)
        return 0;
    for (uint8_t i = 0; i < CUBIES; ++i) {
        if (state->p[i] != i || state->o[i] != 0)
            return 0;
    }
    return 1;
}

static uint8_t heuristic(const state_t *state)
{
    return pdb_distance_at(pattern_rank(state));
}
static uint8_t solution_moves[11];
#define IDA_MAX_DEPTH 11

static int ida_search(const state_t *state,
                      uint8_t remaining,
                      uint8_t last_face,
                      uint8_t depth)
{
    if (remaining == 0)
        return is_solved(state);

    uint8_t next_remaining = (uint8_t) (remaining - 1U);
    state_t next;

    for (uint8_t face = 0; face < 3U; ++face) {
        if (face == last_face)
            continue;

        for (uint8_t turn = 0; turn < 3U; ++turn) {
            uint8_t move = (uint8_t) (face * 3U + turn);
            apply_move_to(state, move, &next);

            if (next_remaining == 0) {
                if (!is_solved(&next))
                    continue;
            } else {
                if (heuristic(&next) > next_remaining)
                    continue;
                if (!ida_search(&next, next_remaining, face,
                                (uint8_t) (depth + 1U)))
                    continue;
            }

            solution_moves[depth] = move;
            return 1;
        }
    }

    return 0;
}

static int ida_solve(const state_t *start)
{
    if (is_solved(start))
        return 0;
    uint8_t start_heuristic = heuristic(start);
    uint8_t bound = start_heuristic;
    while (bound <= IDA_MAX_DEPTH) {
        if (ida_search(start, bound, MOVES, 0))
            return bound;
        ++bound;
    }
    return -1;
}

int rubik_solve(const char *state, char *out, size_t cap)
{
    state_t cube;
    unsigned seen = 0;
    unsigned twist_sum = 0;

    if (state == NULL)
        return -1;

    for (unsigned i = 0; i < CUBIES; ++i) {
        unsigned corner = (unsigned) (state[i] - '1');
        if (corner >= CUBIES || (seen & (1u << corner)) != 0)
            return -1;
        seen |= 1u << corner;
        cube.p[i] = (uint8_t) corner;
    }

    for (unsigned i = 0; i < CUBIES; ++i) {
        unsigned orientation = (unsigned) (state[CUBIES + i] - '1');
        if (orientation >= 3)
            return -1;
        cube.o[i] = (uint8_t) orientation;
        twist_sum += orientation;
        if (twist_sum >= 3)
            twist_sum -= 3;
    }

    if (twist_sum != 0 || state[RUBIK_STATE_LEN] != '\0')
        return -1;

    int depth = ida_solve(&cube);
    if (depth < 0)
        return -1;

    size_t needed = 1;
    for (int i = 0; i < depth; ++i) {
        const char *name = move_names[solution_moves[i]];
        needed += 1 + (name[1] != '\0') + (i != 0);
    }

    if (cap < needed) {
        if (cap != 0)
            out[0] = '\0';
        return -2;
    }

    size_t written = 0;
    for (int i = 0; i < depth; ++i) {
        const char *name = move_names[solution_moves[i]];
        if (i != 0)
            out[written++] = ' ';
        out[written++] = name[0];
        if (name[1] != '\0')
            out[written++] = name[1];
    }
    out[written] = '\0';
    return depth;
}
